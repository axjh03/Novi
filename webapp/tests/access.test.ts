import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import bcrypt from 'bcryptjs';
import { durationDate, licenseKey } from '../src/lib/access-policy';

test('access lifecycle: hierarchy, isolation, permanent licenses and exclusive desktop sessions', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'astra-access-test-'));
  process.env.DATABASE_URL = 'file:' + join(directory, 'test.db').replaceAll('\\', '/');
  process.env.ACCESS_JWT_SECRET = randomBytes(32).toString('hex');
  process.env.ACCESS_ENCRYPTION_KEY = randomBytes(32).toString('hex');
  execFileSync(process.execPath, ['node_modules/prisma/build/index.js', 'migrate', 'deploy'], { cwd: resolve('.'), env: process.env, stdio: 'pipe' });
  const { prisma: db } = await import('../src/lib/db');
  const { login, state, revealCredential, activity, mutate, desktop, authenticate, LEASE_MS } = await import('../src/lib/access');
  const secret = ' correct horse battery staple ';
  const req = (token: string, method = 'POST', desktop = false) => new Request('http://localhost:3000/api/control', { method, headers: desktop ? { authorization: `Bearer ${token}` } : { cookie: `astra_session=${token}` } });
  const sign = (username: string, audience = 'portal', deviceId = 'device-one') => login({ username, password: secret, audience, deviceId, deviceName: deviceId }, new Request('http://localhost:3000/login', { headers: { 'x-forwarded-for': '203.0.113.42, 10.0.0.1' } }));
  try {
    const admin = await db.accessAccount.create({ data: { username: 'admin', name: 'Admin', role: 'ADMIN', passwordHash: await bcrypt.hash(secret, 12) } });
    await assert.rejects(db.accessAccount.create({ data: { username: 'admin2', name: 'Second Admin', role: 'ADMIN', passwordHash: admin.passwordHash } }));
    const a = (await sign('admin')).token;
    const create = async (token: string, username: string, role: string, parentId?: string, licenseId?: string) => {
      await mutate(req(token), 'accounts', undefined, { username, name: username, password: secret, role, parentId, licenseId });
      return db.accessAccount.findUniqueOrThrow({ where: { username } });
    };
    const standalone = await create(a, 'standalone', 'STANDALONE');
    const other = await create(a, 'otherowner', 'STANDALONE');
    const corp = await create(a, 'corporation', 'CORP');
    const c = (await sign(corp.username)).token;
    const subcorp = await create(c, 'subcorp', 'SUBCORP', corp.id);
    const s = (await sign(standalone.username)).token;
    const { manageReleaseArtifacts } = await import('../src/lib/release-manager');
    await assert.rejects(manageReleaseArtifacts(req(s, 'GET'), {}), /Administrator portal access required/);
    await assert.rejects(manageReleaseArtifacts(req(s, 'DELETE'), { confirm: 'delete-artifacts', ids: [1] }), /Administrator portal access required/);
    await assert.rejects(manageReleaseArtifacts(req('', 'GET'), {}));

    const sub = (await sign(subcorp.username)).token;
    await assert.rejects(create(s, 'illegalcorp', 'CORP'), /cannot create/);
    await assert.rejects(create(c, 'illegaldesktop', 'LICENSE', corp.id), /Invalid parent/);
    await assert.rejects(create(a, 'secondadmin', 'ADMIN'), /one administrator/);
    await assert.rejects(sign('admin', 'desktop'), /Ineligible/);
    await assert.rejects(sign('standalone', 'desktop'), /Ineligible/);
    await mutate(req(a), 'licenses', undefined, { ownerId: standalone.id, duration: 1, unit: 'MONTHS' });
    const license = await db.accessLicense.findFirstOrThrow({ where: { ownerId: standalone.id } });
    assert.match(license.key, /^[A-Z0-9]{4}(?:-[A-Z0-9]{4}){3}$/);
    const account = await create(s, 'desktop', 'LICENSE', standalone.id, license.id);
    await assert.rejects(create(s, 'reusedlicense', 'LICENSE', standalone.id, license.id), /unused/);
    assert.equal(await db.accessAccount.count({ where: { username: 'reusedlicense' } }), 0, 'failed binding rolls back account creation');
    await assert.rejects(sign('desktop'), /Desktop accounts must sign in|not eligible/);
    assert.equal((await state(req(s, 'GET'))).accounts.some(x => x.id === other.id), false);
    await assert.rejects(mutate(req(s, 'PATCH'), 'accounts', other.id, { name: 'hacked' }), /Administrator/);
    await mutate(req(s), 'credentials', undefined, { provider: 'OPENAI', nickname: 'Owner primary', secret: 'private-key-one' });
    const key = await db.managedCredential.findFirstOrThrow({ where: { ownerId: standalone.id } });
    assert.equal(key.encryptedSecret.includes('private-key-one'), false);
    assert.equal(key.model, '', 'API key setup does not require a model');
    await mutate(req(s, 'PATCH'), 'credentials', key.id, { provider: 'OPENAI', nickname: 'Renamed primary' });
    assert.equal((await db.managedCredential.findUniqueOrThrow({ where: { id: key.id } })).encryptedSecret, key.encryptedSecret);
    assert.equal(JSON.stringify(await state(req(s, 'GET'))).includes('private-key-one'), false);
    await assert.rejects(mutate(req(sub, 'DELETE'), 'credentials', key.id, {}), /not found/);
    assert.equal((await revealCredential(req(s), key.id)).secret, 'private-key-one');
    assert.equal((await revealCredential(req(a), key.id)).secret, 'private-key-one');
    await assert.rejects(revealCredential(req(sub), key.id), /not found/);
    await assert.rejects(revealCredential(new Request('http://localhost:3000/api/control', { method: 'POST', headers: { cookie: `astra_session=${s}`, origin: 'https://untrusted.example' } }), key.id), /origin/);
    assert.ok((await state(req(a, 'GET'))).accounts.find(x => x.id === standalone.id)?.activity.some(item => item.audience === 'portal' && item.lastSeenAt));

    const d = (await sign('desktop', 'desktop')).token;
    await assert.rejects(revealCredential(req(d, 'POST', true), key.id), /management portal/);
    assert.equal((await state(req(a, 'GET'))).sessions.find(x => x.accountId === account.id)?.ipAddress, '203.0.113.42');
    const heartbeat = new Request('http://localhost:3000/api/control/desktop', { headers: { authorization: `Bearer ${d}`, 'x-real-ip': '198.51.100.24' } });
    assert.equal((await desktop(heartbeat)).credentials[0].apiKey, 'private-key-one');
    assert.equal((await state(req(a, 'GET'))).sessions.find(x => x.accountId === account.id)?.ipAddress, '198.51.100.24');
    await assert.rejects(sign('desktop', 'desktop', 'device-two'), /active on another/);
    await assert.rejects(sign('desktop', 'desktop', 'device-one'), /active on another/, 'same device cannot start another session');
    await assert.rejects(mutate(req(d, 'POST', true), 'credentials', undefined, {}), /read-only/);
    await assert.rejects(authenticate(req(a, 'GET', true)), /session has ended/, 'portal JWT cannot become a desktop JWT');
    await mutate(req(d, 'POST', true), 'logout', undefined, {});
    await assert.rejects(desktop(req(d, 'GET', true)), /session has ended/);
    const concurrent = await Promise.allSettled([sign('desktop', 'desktop', 'device-two'), sign('desktop', 'desktop', 'device-three')]);
    assert.equal(concurrent.filter(r => r.status === 'fulfilled').length, 1, 'simultaneous login grants exactly one session');
    assert.equal(await db.accessSession.count({ where: { activeSlot: account.id } }), 1);
    const staleDesktop = concurrent.find(r => r.status === 'fulfilled')!.value.token;
    await db.accessSession.updateMany({ where: { activeSlot: account.id }, data: { lastSeenAt: new Date(Date.now() - LEASE_MS - 1000) } });
    assert.equal((await desktop(req(staleDesktop, 'GET', true))).user.id, account.id, 'a lapsed lease resumes while no other device has signed in');
    await db.accessSession.updateMany({ where: { activeSlot: account.id }, data: { lastSeenAt: new Date(Date.now() - LEASE_MS - 1000) } });
    const third = (await sign('desktop', 'desktop', 'device-three')).token;
    await assert.rejects(desktop(req(staleDesktop, 'GET', true)), /session has ended/);
    await mutate(req(a, 'PATCH'), 'accounts', account.id, { password: 'new password long enough' });
    await assert.rejects(desktop(req(third, 'GET', true)), /session has ended/);
    await mutate(req(a, 'PATCH'), 'accounts', account.id, { password: secret });
    const renewFrom = +license.expiresAt;
    await mutate(req(a, 'PATCH'), 'licenses', license.id, { action: 'renew', duration: 2, unit: 'DAYS' });
    assert.equal(+(await db.accessLicense.findUniqueOrThrow({ where: { id: license.id } })).expiresAt, renewFrom + 2 * 86400000);
    await mutate(req(a, 'PATCH'), 'licenses', license.id, { action: 'terminate' });
    await assert.rejects(sign('desktop', 'desktop'), /expired or terminated/);
    await assert.rejects(mutate(req(a, 'PATCH'), 'licenses', license.id, { action: 'renew', duration: 1, unit: 'YEARS' }), /cannot be renewed/);
    await assert.rejects(db.accessLicense.update({ where: { id: license.id }, data: { accountId: null } }));
    await assert.rejects(db.accessLicense.delete({ where: { id: license.id } }));
    await mutate(req(sub), 'requests', undefined, { quantity: 2, duration: 1, unit: 'YEARS' });
    const order = await db.licenseRequest.findFirstOrThrow({ where: { ownerId: subcorp.id } });
    await mutate(req(a, 'PATCH'), 'requests', order.id, { status: 'APPROVED' });
    await assert.rejects(mutate(req(a, 'PATCH'), 'requests', order.id, { status: 'APPROVED' }), /already been processed/);
    assert.equal(await db.accessLicense.count({ where: { ownerId: subcorp.id } }), 2);
    const subLicense = await db.accessLicense.findFirstOrThrow({ where: { ownerId: subcorp.id } });
    const subdesktop = await create(sub, 'subdesktop', 'LICENSE', subcorp.id, subLicense.id);
    await mutate(req(c), 'credentials', undefined, { provider: 'ANTHROPIC', nickname: 'Corp key', model: 'test-model', secret: 'corp-secret' });
    await mutate(req(sub), 'credentials', undefined, { provider: 'GEMINI', nickname: 'Studio key', model: 'test-model', secret: 'studio-secret' });
    const inherited = (await sign('subdesktop', 'desktop')).token;
    assert.deepEqual((await desktop(req(inherited, 'GET', true))).credentials.map(x => x.apiKey).sort(), ['corp-secret', 'studio-secret']);
    await mutate(req(sub, 'PATCH'), 'accounts', subdesktop.id, { password: 'subcorp-set desktop password' });
    await assert.rejects(desktop(req(inherited, 'GET', true)), /session has ended/);
    const resetBySubcorp = (await login({ username: 'subdesktop', password: 'subcorp-set desktop password', audience: 'desktop', deviceId: 'subcorp-reset', deviceName: 'subcorp-reset' })).token;
    await mutate(req(c, 'PATCH'), 'accounts', subcorp.id, { password: 'new subcorp password' });
    assert.equal((await desktop(req(resetBySubcorp, 'GET', true))).user.id, subdesktop.id, 'resetting a parent does not end descendant sessions');
    await mutate(req(c, 'PATCH'), 'accounts', subdesktop.id, { password: 'new desktop password' });
    await assert.rejects(mutate(req(c, 'PATCH'), 'accounts', account.id, { password: secret }), /Administrator/);
    await assert.rejects(mutate(req(c, 'PATCH'), 'accounts', subcorp.id, { password: secret, name: 'hacked' }), /Administrator/);
    await assert.rejects(desktop(req(resetBySubcorp, 'GET', true)), /session has ended/);
    assert.equal((await login({ username: 'subcorp', password: 'new subcorp password' })).user.id, subcorp.id);
    assert.equal((await login({ username: 'subdesktop', password: 'new desktop password', audience: 'desktop', deviceId: 'reset-device', deviceName: 'reset-device' })).user.id, subdesktop.id);
    await mutate(req(a, 'PATCH'), 'accounts', corp.id, { status: 'SUSPENDED' });
    await assert.rejects(desktop(req(inherited, 'GET', true)), /session has ended|inactive/);
    await assert.rejects(login({ username: 'subdesktop', password: 'new desktop password', audience: 'desktop', deviceId: 'inactive-device', deviceName: 'inactive-device' }), /inactive/);
    await mutate(req(a, 'DELETE'), 'accounts', standalone.id, {});
    assert.equal((await db.accessLicense.findUniqueOrThrow({ where: { id: license.id } })).accountId, account.id);
    assert.equal((await db.accessAccount.findUniqueOrThrow({ where: { id: account.id } })).status, 'DELETED');
    assert.equal(durationDate(new Date('2028-01-31T12:00:00Z'), 1, 'MONTHS').toISOString(), '2028-02-29T12:00:00.000Z');
    assert.equal(durationDate(new Date('2028-02-29T12:00:00Z'), 1, 'YEARS').toISOString(), '2029-02-28T12:00:00.000Z');
    assert.equal(new Set(Array.from({ length: 1000 }, licenseKey)).size, 1000);
    assert.ok(await db.accessAudit.count() > 10);
    const otherSession = (await sign(other.username)).token;
    const activityRequest = (query = '', token = a) => new Request(`http://localhost:3000/api/control/activity?${query}`, { headers: { cookie: `astra_session=${token}` } });
    await assert.rejects(activity(activityRequest('', otherSession)), /Administrator/);
    await assert.rejects(activity(activityRequest('event=SIGNED_IN')), /account or license event/);
    await assert.rejects(activity(activityRequest('event=toString')), /account or license event/);
    await assert.rejects(activity(activityRequest('page=-1')), /Invalid page/);
    await assert.rejects(activity(activityRequest('sort=invalid')), /newest or oldest/);
    await assert.rejects(activity(activityRequest('from=invalid')), /Invalid date/);
    await assert.rejects(activity(activityRequest('from=2020-01-02T00:00:00Z&to=2020-01-01T00:00:00Z')), /end must be/);
    // More than the old 100-event cap, with noise interspersed and exact range boundaries.
    await db.accessAudit.createMany({ data: Array.from({ length: 125 }, (_, i) => ({ id: `activity-${String(i).padStart(3, '0')}`, actorId: admin.id, action: i % 5 === 0 ? 'SIGNED_IN' : 'ACCOUNT_UPDATED', targetId: other.id, createdAt: new Date(Date.UTC(2020, 0, 1, 0, i)) })) });
    const range = 'from=2020-01-01T00:00:00Z&to=2020-01-01T02:04:00Z';
    const first = await activity(activityRequest(`${range}&sort=asc`));
    assert.equal(first.total, 100);
    assert.equal(first.items.length, 20);
    assert.equal(first.pages, 5);
    assert.equal(first.items[0].id, 'activity-001');
    assert.equal(first.items[0].actorName, '@admin');
    assert.equal(first.items[0].targetName, `@${other.username}`);
    const secondPage = await activity(activityRequest(`${range}&sort=asc&page=2`));
    assert.ok(secondPage.items.every(item => !first.items.some(previous => previous.id === item.id)));
    const last = await activity(activityRequest(`${range}&sort=asc&page=999`));
    assert.equal(last.page, 5);
    assert.equal(last.items.at(-1)?.id, 'activity-124');
    const newest = await activity(activityRequest(`${range}&sort=desc`));
    assert.equal(newest.items[0].id, 'activity-124');
    const exact = await activity(activityRequest('from=2020-01-01T00:01:00Z&to=2020-01-01T00:01:00Z'));
    assert.equal(exact.total, 1);
    const licenseEvents = await activity(activityRequest('event=LICENSE_RENEWED'));
    assert.ok(licenseEvents.total > 0);
    assert.ok(licenseEvents.items.every(item => item.action === 'LICENSE_RENEWED'));
    assert.equal(licenseEvents.items[0].targetName, license.key);
    const empty = await activity(activityRequest(`${range}&event=LICENSE_RENEWED`));
    assert.equal(empty.total, 0);
    assert.equal(empty.page, 1);
    await mutate(req(a, 'PATCH'), 'accounts', admin.id, { password: 'new administrator password' });
    await assert.rejects(state(req(a, 'GET')), /session has ended/);
    assert.equal((await state(req(otherSession, 'GET'))).user.id, other.id, 'admin self-reset does not end other accounts sessions');
    assert.equal((await login({ username: 'admin', password: 'new administrator password' })).user.id, admin.id);
  } finally {
    await db.$disconnect();
    assert.equal(dirname(resolve(directory)), resolve(tmpdir()), 'cleanup must stay in the temporary directory');
    rmSync(directory, { recursive: true, force: true });
  }
});
