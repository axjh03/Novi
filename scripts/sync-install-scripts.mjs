// Generates every copy of the installers from the two sources in webapp/public: the Linux and
// macOS copies of install.sh, and the two Next routes that serve the scripts with the request's
// own origin as the default base URL. Run it after editing install.sh or install.ps1:
//
//   node scripts/sync-install-scripts.mjs          # write the copies
//   node scripts/sync-install-scripts.mjs --check  # exit 1 when a copy is stale (the tests do this)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = file => readFileSync(join(root, file), 'utf8');

const SH_HEADER = '# Novi Unix Automated Provisioner (macOS & Linux)';
const SH_BASE = 'BASE_URL="${NOVI_BASE_URL:-"https://novi-virid.vercel.app"}"';
const PS_BASE = "$baseUrl = if ($env:NOVI_BASE_URL) { $env:NOVI_BASE_URL } else { 'https://novi-virid.vercel.app' }";

/** Escapes a script for a JavaScript template literal. */
const template = source => source.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

/** Every generated file, from the two sources. */
export function generate(sh = read('webapp/public/install.sh'), ps1 = read('webapp/public/install.ps1')) {
  for (const [name, needle] of [['install.sh', SH_HEADER], ['install.sh', SH_BASE], ['install.ps1', PS_BASE]]) {
    const source = name === 'install.sh' ? sh : ps1;
    if (!source.includes(needle)) throw new Error(`${name} no longer contains the line the generator looks for: ${needle}`);
  }
  const linux = sh.replace(SH_HEADER, '# Novi Linux Automated Provisioner (Debian / Ubuntu / Universal AppImage)');
  const mac = sh
    .replace(SH_HEADER, '# Novi macOS Deployment & Provisioning Script\n# Target Architecture: Darwin (arm64 / x86_64)')
    .replace('OS_TYPE="$(uname -s)"\n', 'OS_TYPE="$(uname -s)"\nif [ "${OS_TYPE}" != "Darwin" ]; then printf \'==> ERROR: This script is for macOS. On Linux, use install.sh.\\n\' >&2; exit 1; fi\n');
  const shRoute = `export const dynamic = 'force-dynamic';

// Generated by scripts/sync-install-scripts.mjs from webapp/public/install.sh. Do not edit by hand.
// The only difference from the static file is the default base URL: the host this request came in on.
export async function GET(req: Request) {
  const host = req.headers.get('x-forwarded-host') || req.headers.get('host') || 'novi-virid.vercel.app';
  const proto = req.headers.get('x-forwarded-proto') || (host.startsWith('localhost') ? 'http' : 'https');
  const baseUrl = \`\${proto}://\${host}\`;

  const script = \`${template(sh).replace(template(SH_BASE), "BASE_URL=\\${NOVI_BASE_URL:-'${baseUrl.replace(/'/g, \"'\\\\''\")}'}")}\`;

  return new Response(script, {
    status: 200,
    headers: {
      'Content-Type': 'text/plain; charset=utf-8',
      'Cache-Control': 'no-store, max-age=0',
    },
  });
}
`;
  const psRoute = `export const dynamic = 'force-dynamic';

// Generated by scripts/sync-install-scripts.mjs from webapp/public/install.ps1. Do not edit by hand.
// The only difference from the static file is the default base URL: the host this request came in on.
export async function GET(req: Request) {
  const host = req.headers.get('x-forwarded-host') || req.headers.get('host') || 'novi-virid.vercel.app';
  const proto = req.headers.get('x-forwarded-proto') || (host.startsWith('localhost') ? 'http' : 'https');
  const baseUrl = \`\${proto}://\${host}\`;

  const script = \`${template(ps1).replace(template(PS_BASE), "$baseUrl = if ($env:NOVI_BASE_URL) { $env:NOVI_BASE_URL } else { '${baseUrl.replace(/'/g, \"''\")}' }")}\`;

  return new Response(script, {
    status: 200,
    headers: {
      'Content-Type': 'text/plain; charset=utf-8',
      'Cache-Control': 'no-store, max-age=0',
    },
  });
}
`;
  return {
    'webapp/public/install-linux.sh': linux,
    'scripts/install-mac.sh': mac,
    'webapp/src/app/install.sh/route.ts': shRoute,
    'webapp/src/app/install.ps1/route.ts': psRoute,
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = generate();
  const stale = Object.entries(files).filter(([file, content]) => { try { return read(file) !== content; } catch { return true; } });
  if (process.argv.includes('--check')) {
    if (stale.length) { console.error('Stale installer copies, run node scripts/sync-install-scripts.mjs:\n  ' + stale.map(([f]) => f).join('\n  ')); process.exit(1); }
    console.log('Installer copies are current.');
  } else {
    for (const [file, content] of stale) { writeFileSync(join(root, file), content); console.log('wrote ' + file); }
    if (!stale.length) console.log('Installer copies were already current.');
  }
}
