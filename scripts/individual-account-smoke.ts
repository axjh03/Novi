// Use only with a local webapp pointed at a disposable test schema; this creates test accounts/licenses.
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';

async function main() {
  const baseURL = process.env.TEST_WEB_URL || 'http://127.0.0.1:3137';
  const database = new URL(process.env.DATABASE_URL || 'postgresql://unset');
  assert(['127.0.0.1', 'localhost'].includes(new URL(baseURL).hostname));
  assert(['127.0.0.1', 'localhost'].includes(database.hostname) && database.searchParams.get('schema')?.startsWith('novi_browser_test_'), 'Use a disposable local test schema.');
  assert(process.env.ADMIN_PASSWORD && process.env.ADMIN_USERNAME);
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH });
  const context = await browser.newContext({ baseURL, viewport: { width: 1360, height: 1000 } });
  const page = await context.newPage();
  page.setDefaultTimeout(45_000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const username = `ui.person.${Date.now()}`, password = 'test-only-personal-password';
  const state = async () => {
    const response = await context.request.get('/api/control/state');
    assert(response.ok());
    return (await response.json()).data;
  };
  try {
    await mkdir('.test-data', { recursive: true });
    await page.goto('/');
    assert.equal(await page.title(), 'NOVI');
    assert.equal(await page.locator('#landing-title').innerText(), 'Fuck LeetCode.\nFuck HackerRank.\nFuck Assessment.\nFuck it RAW.');
    assert(await page.getByText('(Random Access Wisdom)', { exact: true }).isVisible());
    const body = await page.locator('body').innerText();
    for (const removed of ['macOS · Windows · Linux', 'Bring your own AI provider', 'Your context. A clearer next step.', 'Bring the backup']) assert(!body.includes(removed));
    assert(await page.getByRole('button', { name: 'YouTube demo coming soon', exact: true }).isDisabled());
    await page.evaluate(() => { (window as any).navigationCheck = 'preserved'; });
    await page.getByRole('button', { name: 'Context', exact: true }).click();
    await page.locator('.public-nav .brand').click();
    assert.equal(await page.evaluate(() => (window as any).navigationCheck), 'preserved', 'the home logo does not reload the current page');
    assert.equal(await page.getByRole('button', { name: 'Context', exact: true }).getAttribute('aria-pressed'), 'true');
    const testimonials = page.locator('section[aria-labelledby="testimonials-title"]');
    assert((await testimonials.innerText()).includes('Sample content.'));
    const rows = testimonials.getByRole('region');
    assert.equal(await rows.count(), 2);
    assert.deepEqual(await rows.locator(':scope > div').evaluateAll(tracks => tracks.map(track => getComputedStyle(track).animationDirection)), ['normal', 'reverse']);
    await testimonials.getByRole('button', { name: 'Pause', exact: true }).click();
    assert.deepEqual(await rows.locator(':scope > div').evaluateAll(tracks => tracks.map(track => getComputedStyle(track).animationPlayState)), ['paused', 'paused']);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert.deepEqual(await rows.locator(':scope > div').evaluateAll(tracks => tracks.map(track => getComputedStyle(track).animationName)), ['none', 'none']);
    await page.screenshot({ path: '.test-data/testimonials-desktop.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await testimonials.scrollIntoViewIfNeeded();
    await page.screenshot({ path: '.test-data/testimonials-mobile.png' });
    await page.getByRole('link', { name: 'Create your account', exact: true }).click();
    assert.equal(await page.evaluate(() => (window as any).navigationCheck), 'preserved', 'signup opens without reloading the landing page');
    await page.getByLabel('Full name', { exact: true }).fill('Personal Browser Test');
    await page.getByLabel('Username', { exact: true }).fill(username);
    await page.getByLabel('Password', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Create individual account', exact: true }).click();
    await page.getByRole('heading', { name: 'Your individual account', exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'User management', exact: true }).count(), 0);
    assert.equal((await state()).accounts.length, 1);
    assert.equal((await state()).licenses.length, 0);
    assert((await context.cookies()).some(cookie => cookie.name === 'astra_session' && cookie.httpOnly && cookie.sameSite === 'Lax'));
    const desktopLogin = () => context.request.post('/api/control/login', { headers: { 'x-novi-plans': '1' }, data: { username, password, audience: 'desktop', deviceId: 'ui-personal-device', deviceName: 'Personal browser test device' } });
    assert.equal((await desktopLogin()).status(), 403, 'signup alone grants no desktop license');
    await page.getByRole('button', { name: 'Licenses', exact: true }).click();
    await page.getByRole('button', { name: 'Request my license', exact: true }).click();
    const dialog = page.getByRole('dialog');
    assert.equal(await dialog.getByLabel('Quantity').count(), 0);
    assert.equal(await dialog.getByLabel('License owner', { exact: true }).count(), 0);
    await dialog.getByLabel(/^Plan/).selectOption('PRO');
    await dialog.getByRole('button', { name: 'Submit request', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Request submitted for administrator review.' }).waitFor();
    await page.getByRole('button', { name: 'API management', exact: true }).click();
    await page.getByRole('button', { name: 'Add API key', exact: true }).click();
    await dialog.getByLabel('Nickname', { exact: true }).fill('Personal test provider');
    await dialog.getByLabel(/^API key/).fill('test-personal-provider-secret');
    await dialog.getByRole('button', { name: 'Save changes', exact: true }).click();
    await page.getByRole('heading', { name: 'Personal test provider', exact: true }).waitFor();
    await page.setViewportSize({ width: 1360, height: 1000 });
    const adminContext = await browser.newContext({ baseURL, viewport: { width: 1360, height: 1000 } });
    const admin = await adminContext.newPage();
    admin.setDefaultTimeout(20_000);
    admin.on('pageerror', error => errors.push(error.message));
    await admin.goto('/#signin');
    await admin.getByLabel('Username', { exact: true }).fill(process.env.ADMIN_USERNAME!);
    await admin.getByLabel('Password', { exact: true }).fill(process.env.ADMIN_PASSWORD!);
    await admin.getByRole('button', { name: 'Sign in', exact: true }).click();
    await admin.getByRole('button', { name: 'User management', exact: true }).click();
    for (const [role, name] of [['INDIVIDUAL', 'Another individual'], ['CORP', 'Enterprise test team']]) {
      await admin.getByRole('button', { name: 'Create account', exact: true }).click();
      const form = admin.getByRole('dialog');
      assert.equal(await form.getByLabel(/^Account type/).inputValue(), 'INDIVIDUAL');
      await form.getByLabel(/^Account type/).selectOption(role);
      assert.equal(await form.getByLabel(/^Parent account/).count(), 0);
      await form.getByLabel('Display name', { exact: true }).fill(name);
      await form.getByLabel('Username', { exact: true }).fill(`${username}.${role.toLowerCase()}`);
      await form.getByLabel(/^Initial password/).fill(password);
      await form.getByRole('button', { name: 'Save changes', exact: true }).click();
      await form.waitFor({ state: 'detached' });
    }
    await admin.locator('.sidebar').getByRole('button', { name: /^Purchase requests/ }).click();
    await admin.getByRole('row').filter({ hasText: username }).getByRole('button', { name: 'Approve', exact: true }).click();
    await admin.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click();
    await admin.getByRole('status').filter({ hasText: 'Changes saved.' }).waitFor();
    await page.getByRole('button', { name: 'Refresh workspace', exact: true }).click();
    const person = await state();
    assert.equal(person.licenses.length, 1);
    assert.equal(person.licenses[0].accountId, person.user.id);
    assert.equal(person.accounts.length, 1);
    const login = await desktopLogin();
    assert(login.ok());
    const token = (await login.json()).data.token;
    const desktop = () => context.request.get('/api/control/desktop', { headers: { authorization: `Bearer ${token}`, 'x-novi-plans': '1' } });
    const desktopResponse = await desktop();
    assert(desktopResponse.ok());
    assert.deepEqual((await desktopResponse.json()).data.credentials.map((c: any) => c.apiKey), ['test-personal-provider-secret']);
    await page.getByRole('button', { name: 'Overview', exact: true }).click();
    await page.getByRole('button', { name: 'Refresh workspace', exact: true }).click();
    await page.getByRole('button', { name: 'End desktop session', exact: true }).waitFor();
    await page.evaluate(() => { (window as any).navigationCheck = 'workspace'; });
    await page.locator('.sidebar .brand').click();
    assert.equal(await page.evaluate(() => (window as any).navigationCheck), 'workspace');
    await page.screenshot({ path: '.test-data/individual-overview.png' });
    await page.getByRole('button', { name: 'End desktop session', exact: true }).click();
    await dialog.getByRole('button', { name: 'Confirm', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    assert.equal((await desktop()).status(), 401);
    assert.equal((await state()).user.id, person.user.id, 'ending desktop does not end web access');
    assert.deepEqual(errors, []);
    console.log('Individual signup, admin account creation, direct license approval, shared web/desktop identity, own keys, session controls, logo navigation, and landing previews passed against PostgreSQL.');
  } catch (error) {
    console.error({ errors, page: (await page.locator('body').innerText()).slice(-2500) });
    await page.screenshot({ path: '.test-data/individual-failure.png' });
    throw error;
  } finally { await browser.close(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
